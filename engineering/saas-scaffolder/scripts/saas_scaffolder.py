def build_tree(payments, tenancy, auth, features, next_major=16):
    """Return the list of relative file paths for the project."""
    files = ["proxy.ts" if next_major >= 16 else "middleware.ts"] + [
        "app/(auth)/login/page.tsx", "app/(auth)/register/page.tsx", "app/(auth)/layout.tsx",
        "app/(dashboard)/dashboard/page.tsx", "app/(dashboard)/settings/page.tsx", "app/(dashboard)/layout.tsx",
        "app/(marketing)/page.tsx", "app/(marketing)/pricing/page.tsx", "app/(marketing)/layout.tsx",
        "app/api/health/route.ts", "app/layout.tsx", "app/not-found.tsx", "app/globals.css",
        "components/dashboard/sidebar.tsx", "components/dashboard/header.tsx",
        "components/marketing/hero.tsx", "components/marketing/pricing-card.tsx",
        "lib/db.ts", "lib/validations.ts", "lib/utils.ts", "db/schema.ts", "db/seed.ts",
        "hooks/use-current-user.ts", ".env.example", "drizzle.config.ts",
        "postcss.config.mjs", "next.config.ts", "package.json", "tsconfig.json", "README.md",
    ]
    if auth == "nextauth":
        files += ["app/api/auth/[...nextauth]/route.ts", "lib/auth.ts"]
    if tenancy != "none":
        files += ["app/(dashboard)/settings/team/page.tsx", f"hooks/use-current-{tenancy}.ts"]
    if payments != "none":
        files += [f"app/api/webhooks/{payments}/route.ts", "app/api/billing/checkout/route.ts",
                  "app/api/billing/portal/route.ts", "app/(dashboard)/settings/billing/page.tsx",
                  "components/billing/plan-card.tsx", "lib/billing.ts", "hooks/use-subscription.ts"]
    for feat in features:
        slug = re.sub(r"[^a-z0-9-]+", "-", feat.lower()).strip("-")
        if slug:
            files.append(f"app/(dashboard)/{slug}/page.tsx")
    return sorted(set(files))


def render_tree(name, files):
    """Render file paths as an indented tree."""
    lines, seen = [f"{name}/"], set()
    for path in files:
        parts = path.split("/")
        for depth in range(1, len(parts)):
            d = "/".join(parts[:depth])
            if d not in seen:
                seen.add(d)
                lines.append("  " * depth + parts[depth - 1] + "/")
        lines.append("  " * len(parts) + parts[-1])
    return "\n".join(lines)


def schema_ts(tenancy, payments):
    """Billing columns live on the tenant table, or on users when there is no tenancy."""
    prefix = "stripe" if payments == "stripe" else "billing"
    billing = BILLING_COLS.replace("{p}", prefix) if payments != "none" else ""
    users = USERS.replace("{billing}", billing if tenancy == "none" else "")
    return SCHEMA_HEAD + users + ("" if tenancy == "none" else TENANT.format(t=tenancy, billing=billing))


def package_json(args):
    deps = dict(BASE_DEPS, **AUTH_DEPS[args.auth], **DB_DEPS[args.db], **PAY_DEPS[args.payments])
    deps["next"] = f"^{args.next_major}.0.0"  # keep the range in step with proxy.ts vs middleware.ts
    return json.dumps({
        "name": args.name, "version": "0.1.0", "private": True,
        "scripts": {"dev": "next dev", "build": "next build", "start": "next start", "lint": "eslint .",
                    "db:generate": "drizzle-kit generate", "db:migrate": "drizzle-kit migrate",
                    "db:seed": "tsx db/seed.ts"},
        "dependencies": dict(sorted(deps.items())), "devDependencies": dict(sorted(DEV_DEPS.items())),
    }, indent=2) + "\n"


def stub(path):
    """Content for a file the tool does not implement."""
    source = next((src for prefix, src in STUB_SOURCES if path.startswith(prefix)), None)
    note = f"Implement from the saas-scaffolder skill: {source}." if source else "Implement for your product."
    if path.endswith((".ts", ".tsx")):
        return f"// STUB generated by saas_scaffolder.py. {note}\nexport {{}}\n"
    if path.endswith(".css"):
        return '@import "tailwindcss";\n'
    return ""


def content_for(path, args):
    fixed = {
        "package.json": lambda: package_json(args),
        ".env.example": lambda: "\n".join(ENV_BLOCKS[k] for k in ("app", "db", args.auth, args.payments)
                                          if k in ENV_BLOCKS),
        "proxy.ts": lambda: MIDDLEWARE[args.auth].replace("{fn}", "proxy"),  # Next 16+
        "middleware.ts": lambda: MIDDLEWARE[args.auth].replace("{fn}", "middleware"),
        "drizzle.config.ts": lambda: DRIZZLE_CONFIG,
        "db/schema.ts": lambda: schema_ts(args.tenancy, args.payments),
        "app/api/health/route.ts": lambda: HEALTH,
        "next.config.ts": lambda: NEXT_CONFIG,
        "tsconfig.json": lambda: json.dumps(TSCONFIG, indent=2) + "\n",
        "postcss.config.mjs": lambda: "export default { plugins: { '@tailwindcss/postcss': {} } }\n",
        "README.md": lambda: (f"# {args.name}\n\nScaffolded: auth={args.auth}, db={args.db}, payments={args.payments}, "
                              f"tenancy={args.tenancy}.\n\n1. `npm install` once and commit the lockfile: deps without a `^` range use npm tags,\n"
                              "   so the lockfile is what makes installs reproducible.\n"
                              + ("   Auth.js is now part of Better Auth; check authjs.dev before a new auth setup.\n"
                                 if args.auth == "nextauth" else "") + "2. Copy `.env.example` to `.env.local` and fill it in.\n"
                              "3. `npm run db:generate && npm run db:migrate`.\n"
                              "4. Replace every `// STUB` file (`grep -rl 'STUB generated' .`).\n"),
    }
    return fixed[path]() if path in fixed else stub(path)


def fail(msg):
    sys.exit(print(f"error: {msg}", file=sys.stderr) or 2)

def main():
    parser = argparse.ArgumentParser(
        description="Lay down a Next.js SaaS skeleton: tree, provider-specific package.json, .env.example, "
                    "Drizzle schema and middleware; other files are stubs that point at the references.",
        epilog="example: %(prog)s --name acme --auth clerk --payments none --output /tmp/acme --dry-run")
    parser.add_argument("--name", required=True, help="npm package name: lowercase letters, digits, - . _")
    parser.add_argument("--output", default=None, help="Output directory (default: ./<name>); must be empty or absent")
    parser.add_argument("--auth", choices=sorted(AUTH_DEPS), default="nextauth", help="Auth provider")
    parser.add_argument("--db", choices=sorted(DB_DEPS), default="neondb", help="Postgres host (driver dependency)")
    parser.add_argument("--payments", choices=sorted(PAY_DEPS), default="stripe", help="Billing provider")
    parser.add_argument("--tenancy", choices=["workspace", "organization", "none"], default="workspace",
                        help="Tenancy model (shapes the schema)")
    parser.add_argument("--features", default="", help="Comma-separated extra dashboard pages")
    parser.add_argument("--next-major", type=int, default=16, help="Next.js major: 16+ writes proxy.ts, older middleware.ts")
    parser.add_argument("--dry-run", action="store_true", help="Print the plan without writing files")
    parser.add_argument("--format", choices=["text", "json"], default="text", help="Output format")
    parser.add_argument("--json", action="store_const", const="json", dest="format", help="Same as --format json")
    args = parser.parse_args()

    if not re.fullmatch(r"[a-z0-9][a-z0-9._-]{0,213}", args.name):
        fail(f"--name {args.name!r} is not a valid npm package name (lowercase letters, digits, '-', '.', '_')")
    output_dir = os.path.abspath(args.output or os.path.join(".", args.name))
    if os.path.exists(output_dir) and (not os.path.isdir(output_dir) or os.listdir(output_dir)):
        fail(f"{output_dir} exists and is not an empty directory; refusing to overwrite")
    features = [f.strip() for f in args.features.split(",") if f.strip()]
    files = build_tree(args.payments, args.tenancy, args.auth, features, args.next_major)

    written, stubs = [], []
    for rel in files:
        text = content_for(rel, args)
        stubs += [rel] if text.startswith("// STUB") else []
        if args.dry_run:
            continue
        path = os.path.join(output_dir, rel)
        try:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
        except OSError as e:
            fail(f"cannot write {path}: {e.strerror}")
        written.append(rel)

    pkg = json.loads(package_json(args))
    result = {
        "project_name": args.name, "output_directory": output_dir, "auth_provider": args.auth,
        "database_provider": args.db, "payment_provider": args.payments, "tenancy_model": args.tenancy,
        "extra_features": features, "dry_run": args.dry_run, "files_planned": len(files),
        "files_written": len(written), "stub_files": stubs, "dependencies": sorted(pkg["dependencies"]),
        "tree": render_tree(args.name, files), "generated_at": datetime.now(timezone.utc).isoformat(),
    }
    if args.format == "json":
        return print(json.dumps(result, indent=2))
    print(f"SaaS Scaffolder: {args.name}  (auth={args.auth}, db={args.db}, payments={args.payments}, "
          f"tenancy={args.tenancy})")
    print(f"Output: {output_dir}{'  [dry run: nothing written]' if args.dry_run else ''}\n\n{result['tree']}")
    print(f"\nDependencies: {', '.join(result['dependencies'])}")
    print(f"{len(files) - len(stubs)} files with content, {len(stubs)} stubs to implement "
          f"(each names its reference section).")
    print("next/react/tailwind use ^ ranges; other deps use npm tags. Run npm install once and commit the lockfile.")


if __name__ == "__main__":
    main()
